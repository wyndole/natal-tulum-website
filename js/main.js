const EN = {};
document.querySelectorAll("[data-i18n]").forEach(el => EN[el.dataset.i18n] = el.textContent);

function setLang(lang){
  const dict = lang === "es" ? ES : EN;
  document.querySelectorAll("[data-i18n]").forEach(el => { const t = dict[el.dataset.i18n]; if (t) el.textContent = t; });
  document.documentElement.lang = lang;
  document.getElementById("lang").textContent = lang === "es" ? "EN" : "ES";
  try { localStorage.setItem("lang", lang); } catch(e){}
  try { renderAround(); } catch(e){}  // not ready yet on first load
}
document.getElementById("lang").addEventListener("click", () =>
  setLang(document.documentElement.lang === "es" ? "en" : "es"));
try { if (localStorage.getItem("lang") === "es") setLang("es"); } catch(e){}

document.getElementById("year").textContent = new Date().getFullYear();

// Gallery + Around Tulum: built from gallery.json (generated by scripts/build_gallery.py)
let photos = [], around = [], set = [], current = 0;
const lb = document.getElementById("lightbox"), lbImg = lb.querySelector("img");
const isEs = () => document.documentElement.lang === "es";
const cap = p => (isEs() && p.alt_es) ? p.alt_es : (p.alt || "");
function show(list, i){ set = list; current = (i + set.length) % set.length; lbImg.src = set[current].full; lbImg.alt = cap(set[current]); lb.hidden = false; }
lb.querySelector(".lb-close").onclick = () => lb.hidden = true;
lb.querySelector(".lb-prev").onclick = () => show(set, current - 1);
lb.querySelector(".lb-next").onclick = () => show(set, current + 1);
lb.addEventListener("click", e => { if (e.target === lb) lb.hidden = true; });
document.addEventListener("keydown", e => {
  if (lb.hidden) return;
  if (e.key === "Escape") lb.hidden = true;
  if (e.key === "ArrowLeft") show(set, current - 1);
  if (e.key === "ArrowRight") show(set, current + 1);
});

function renderAround(){
  const box = document.getElementById("around"); if (!box) return;
  box.innerHTML = "";
  around.forEach((p, i) => {
    const f = document.createElement("figure");
    f.innerHTML = `<button><img src="${p.thumb}" alt="${cap(p)}" loading="lazy"></button><figcaption>${cap(p)}</figcaption>`;
    f.querySelector("button").onclick = () => show(around, i);
    box.appendChild(f);
  });
}

fetch("gallery.json").then(r => r.json()).then(list => {
  photos = list.filter(p => !p.group);
  around = list.filter(p => p.group === "around");
  renderAround();
  if (!photos.length) return;
  const hero = photos.find(p => p.hero) || photos[0];
  document.getElementById("hero").style.backgroundImage =
    `linear-gradient(180deg,rgba(0,0,0,0) 30%,rgba(0,0,0,.55)), url("${hero.full}")`;
  const grid = document.getElementById("grid"); grid.innerHTML = "";
  photos.forEach((p, i) => {
    const b = document.createElement("button");
    b.innerHTML = `<img src="${p.thumb}" alt="${p.alt || ""}" loading="lazy">`;
    b.onclick = () => show(photos, i);
    grid.appendChild(b);
  });
}).catch(() => {});
